"""Independent generator for the GS-103 golden fixtures (design-v0.2 §7.3/§7.4).

It lays out every field with struct and computes CRC-16/CCITT-FALSE bitwise; it does not use the Java encoder, so a
golden-fixture test that passes is an independent check of the layout. Never regenerate fixtures with the Java code.

Usage (from the repository root; Python 3, standard library only):
    python tools/gen_fixtures.py src/test/resources/fixtures/v1
The output must be byte-identical to the committed files: `git diff --exit-code src/test/resources/fixtures/v1`.
"""
import gzip, struct, os, sys

out_dir = sys.argv[1]

def crc16_ccitt_false(data):
    crc = 0xFFFF
    for byte in data:
        crc ^= byte << 8
        for _ in range(8):
            crc = ((crc << 1) ^ 0x1021) if crc & 0x8000 else (crc << 1)
            crc &= 0xFFFF
    return crc

assert crc16_ccitt_false(b"123456789") == 0x29B1

def emit(name, header, fields):
    lines = ["# " + h for h in header]
    total = b""
    for label, raw in fields:
        lines.append(" ".join("%02x" % b for b in raw).ljust(72) + "# " + label)
        total += raw
    with open(os.path.join(out_dir, name), "w", newline="\n", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    return total

