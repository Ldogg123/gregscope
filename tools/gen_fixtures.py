# --- registry.dat (section 8.3): gzipped NBT, written here without any NBT library ---

TAG_END, TAG_BYTE, TAG_INT, TAG_LONG, TAG_STRING, TAG_LIST, TAG_COMPOUND = 0, 1, 3, 4, 8, 9, 10

def nbt_name(text):
    raw = text.encode("utf-8")
    return struct.pack(">H", len(raw)) + raw

def nbt_tag(tag_id, name, payload):
    return bytes([tag_id]) + nbt_name(name) + payload

def nbt_byte(name, value):
    return nbt_tag(TAG_BYTE, name, struct.pack(">b", value))

def nbt_int(name, value):
    return nbt_tag(TAG_INT, name, struct.pack(">i", value))

def nbt_long(name, value):
    return nbt_tag(TAG_LONG, name, struct.pack(">q", value))

def nbt_string(name, value):
    return nbt_tag(TAG_STRING, name, nbt_name(value))

def nbt_compound_payload(entries):
    return b"".join(entries) + bytes([TAG_END])

def nbt_compound(name, entries):
    return nbt_tag(TAG_COMPOUND, name, nbt_compound_payload(entries))

def nbt_compound_list(name, elements):
    payload = bytes([TAG_COMPOUND]) + struct.pack(">i", len(elements))
    return nbt_tag(TAG_LIST, name, payload + b"".join(nbt_compound_payload(e) for e in elements))

