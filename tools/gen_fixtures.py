def reg_entry(msb, lsb, kind, dim, x, y, z, side, owner, label, meta_id, meta, machine, status, state, cause,
              created, seen, since, extra=None):
    fields = [nbt_long("idM", msb), nbt_long("idL", lsb), nbt_byte("kind", kind), nbt_int("dim", dim),
              nbt_int("x", x), nbt_int("y", y), nbt_int("z", z), nbt_byte("side", side)]
    if owner is not None:
        fields += [nbt_long("owM", owner[0]), nbt_long("owL", owner[1]), nbt_string("owN", owner[2])]
    fields += [nbt_string("lbl", label), nbt_int("mi", meta_id), nbt_string("mn", meta),
               nbt_string("nm", machine), nbt_string("st", status), nbt_byte("state", state),
               nbt_byte("cause", cause), nbt_long("ct", created), nbt_long("seen", seen), nbt_long("since", since)]
    if extra:
        fields += extra
    return fields

