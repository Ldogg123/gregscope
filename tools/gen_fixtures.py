def crc32_ieee(data):
    """CRC-32 (IEEE 802.3), computed bitwise so it shares no code with zlib."""
    crc = 0xFFFFFFFF
    for byte in data:
        crc ^= byte
        for _ in range(8):
            crc = (crc >> 1) ^ 0xEDB88320 if crc & 1 else crc >> 1
    return crc ^ 0xFFFFFFFF

assert crc32_ieee(b"123456789") == 0xCBF43926

# A pinned sensor UUID; any value works, the test uses the same one.
GSH_UUID_MSB = 0x3FA2C1D0A1B24C3D
GSH_UUID_LSB = -0x5E6F708192A3B4C5      # a negative low half, so sign handling is covered
GSH_CREATED = 1_759_000_000

def gsh_header(format_version, sensor_kind, slot_layout, msb, lsb, created, break_crc=False):
    fields = [
        ("off 0  4 B magic GSH1", b"GSH1"),
        ("off 4  u16 formatVersion = %d" % format_version, struct.pack(">H", format_version)),
        ("off 6  u16 slotSize = 64", struct.pack(">H", 64)),
        ("off 8  u16 slotCount = 1440", struct.pack(">H", 1440)),
        ("off 10 u8  sensorKind = %d" % sensor_kind, struct.pack(">B", sensor_kind)),
        ("off 11 u8  slotLayout = %d" % slot_layout, struct.pack(">B", slot_layout)),
        ("off 12 i64 uuid msb", struct.pack(">q", msb)),
        ("off 20 i64 uuid lsb", struct.pack(">q", lsb)),
        ("off 28 i64 createdEpochSec = %d" % created, struct.pack(">q", created)),
        ("off 36 24 B reserved = 0", bytes(24)),
    ]
    body = b"".join(raw for _, raw in fields)
    assert len(body) == 60
    crc = crc32_ieee(body)
    if break_crc:
        crc ^= 0x00000001
    fields.append(("off 60 u32 CRC-32 of bytes 0..59 = 0x%08x%s"
                   % (crc, " (deliberately wrong)" if break_crc else ""),
                   struct.pack(">I", crc)))
    return fields

